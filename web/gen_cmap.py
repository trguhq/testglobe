#!/usr/bin/env python3
"""Generate the browser palette from the native palette; --check never writes."""
from pathlib import Path
import argparse
import re
import sys


def earth_palette_source(source):
    text = re.sub(r"/\*.*?\*/", "", source.read_text(encoding="utf-8"), flags=re.S)
    match = re.search(r"\bearth_cmap\s*\[256\]\s*\[3\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
    if match is None:
        raise ValueError("cannot find earth_cmap[256][3]")
    triple = r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}"
    body = match.group(1)
    entries = re.findall(triple, body)
    remainder = re.sub(triple, "", body)
    if len(entries) != 256 or re.sub(r"[\s,]", "", remainder):
        raise ValueError("palette must contain exactly 256 RGB triples")
    values = [int(channel) for entry in entries for channel in entry]
    if any(channel > 255 for channel in values):
        raise ValueError("palette channels must be bytes")
    return values


def earth_palette_module(values):
    lines = ["/* Generated by web/gen_cmap.py from src/e_cmap.h; do not edit.",
             " * SPDX-License-Identifier: GPL-3.0-or-later */",
             "export const earth_palette = new Uint8Array(["]
    for offset in range(0, len(values), 24):
        lines.append("    " + ", ".join(str(value) for value in values[offset:offset + 24]) + ",")
    lines.append("]);\n")
    return "\n".join(lines)


def earth_main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated palette is stale")
    options = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    destination = root / "web" / "e_cmap.js"
    try:
        expected = earth_palette_module(earth_palette_source(root / "src" / "e_cmap.h"))
        if options.check:
            if not destination.exists() or destination.read_bytes() != expected.encode("utf-8"):
                print("Browser palette is stale; run python3 web/gen_cmap.py", file=sys.stderr)
                return 1
        else:
            destination.write_bytes(expected.encode("utf-8"))
    except (OSError, ValueError) as error:
        print(f"Cannot generate browser palette: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(earth_main())
